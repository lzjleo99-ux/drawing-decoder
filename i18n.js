function getLang() {
  try {
    const v = localStorage.getItem(LS_LANG);
    if (LANGS.indexOf(v) >= 0) return v;
  } catch (e) {}
  const nav = (navigator.language || '').toLowerCase();
  if (nav.indexOf('sr') === 0) return 'sr';
  if (nav.indexOf('zh') === 0) return 'zh';
  return 'en';
}
function setLang(v) {
  if (LANGS.indexOf(v) < 0) return;
  try { localStorage.setItem(LS_LANG, v); } catch (e) {}
}

/** 界面文案：t('btn.pdf') */
function t(key) {
  const lang = getLang();
  const row = UI[key];
  if (!row) return key;
  return row[lang] || row.zh || key;
}

/** 报告里的边框文字（表头/小节标题/字段名）：中文原文若在表里就按当前语言替换，否则原样返回 */
function TX(zh) {
  const lang = getLang();
  if (lang === 'zh') return zh;
  const row = TX_MAP[zh];
  if (!row) return zh;
  const idx = lang === 'en' ? 0 : 1;
  return row[idx] || zh;
}

/** 把 [data-i18n]/[data-i18n-html]/[data-i18n-ph]/[data-i18n-aria]/[data-i18n-title] 都刷新成当前语言 */
function applyI18n(root) {
  const scope = root || document;
  scope.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.getAttribute('data-i18n')); });
  scope.querySelectorAll('[data-i18n-html]').forEach(el => { el.innerHTML = t(el.getAttribute('data-i18n-html')); });
  scope.querySelectorAll('[data-i18n-ph]').forEach(el => { el.placeholder = t(el.getAttribute('data-i18n-ph')); });
  scope.querySelectorAll('[data-i18n-aria]').forEach(el => { el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria'))); });
  scope.querySelectorAll('[data-i18n-title]').forEach(el => { el.setAttribute('title', t(el.getAttribute('data-i18n-title'))); });
  document.documentElement.setAttribute('lang', getLang() === 'zh' ? 'zh-CN' : getLang());
}
